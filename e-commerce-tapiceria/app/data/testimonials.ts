// Helper functions for working with testimonials
export const getFeaturedTestimonials = (): Testimonial[] => {
  return testimonials.filter((testimonial) => testimonial.featured);
};

export const getRecentTestimonials = (count: number = 5): Testimonial[] => {
  return [...testimonials]
    .sort((a, b) => new Date(b.date).getTime() - new Date(a.date).getTime())
    .slice(0, count);
};

export const getTestimonialsByRating = (rating: number): Testimonial[] => {
  return testimonials.filter((testimonial) => testimonial.rating === rating);
};

export const getTestimonialsByProduct = (productId: string): Testimonial[] => {
  return testimonials.filter((testimonial) =>
    testimonial.productIds.includes(productId)
  );
};

export default testimonials;
